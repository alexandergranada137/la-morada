import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
const hash=createHash('sha256');
async function scan(directory){
  for(const entry of (await fs.readdir(directory,{withFileTypes:true})).sort((a,b)=>a.name.localeCompare(b.name))){
    const file=path.join(directory,entry.name);
    if(entry.isDirectory())await scan(file);
    else if(entry.name!=='sw.js'&&!/\.(mp4|pdf|jpg|png|webp|woff2?)$/i.test(entry.name)){hash.update(file);hash.update(await fs.readFile(file));}
    else if(entry.name!=='sw.js'){const stat=await fs.stat(file);hash.update(file+':'+stat.size+':'+stat.mtimeMs);}
  }
}
await scan('public');
const template=await fs.readFile('scripts/cache-worker.template.js','utf8');hash.update(template);
const release=hash.digest('hex').slice(0,16);
await fs.writeFile('public/sw.js',template.replace('__CACHE_RELEASE__',release));
await fs.writeFile('lib/cache-release.ts',`// Generated by scripts/prepare-cache.mjs.\nexport const CACHE_RELEASE = '${release}';\n`);
console.log('Prepared browser cache release '+release);
