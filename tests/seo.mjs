import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const seo={};new Function('exports',ts.transpile(fs.readFileSync('lib/seo.ts','utf8'),{module:ts.ModuleKind.CommonJS}))(seo);
const origin='https://morada.test';
const sitemap=seo.sitemapXml(origin);
const titles=new Set(),descriptions=new Set();
for(const [path,page] of Object.entries(seo.PUBLIC_PAGES)){
  assert.equal(seo.canonicalPath(path),path);
  const alias=path==='/'?'/index.html':path+'.html';
  assert.equal(seo.canonicalPath(alias),path);
  assert.equal(seo.canonicalPath(path+'/'),path);
  assert.ok(sitemap.includes('<loc>'+origin+path+'</loc>'));
  const tags=seo.pageMetadata(origin,path);
  assert.equal((tags.match(/rel="canonical"/g)||[]).length,1);
  assert.ok(tags.includes('content="index,follow,max-image-preview:large"'));
  const graph=JSON.parse(tags.match(/<script type="application\/ld\+json">(.*?)<\/script>/)[1])['@graph'];
  const document=graph.find(node=>node['@id']===origin+path+'#pagina');
  assert.equal(document.url,origin+path);assert.equal(document.name,page.title);
  if(path!=='/')assert.equal(graph.find(node=>node['@type']==='BreadcrumbList').itemListElement[1].item,origin+path);
  assert.ok(!graph.some(node=>node['@type']==='Review'||node['@type']==='AggregateRating'||node['@type']==='VideoObject'),'No invented reviews, ratings or background-video markup');
  const file='public/'+(path==='/'?'index':path.slice(1))+'.html';
  const html=fs.readFileSync(file,'utf8');
  assert.ok(html.includes('<title>'+seo.escapeHtml(page.title)+'</title>'),file+' title must agree with metadata');
  assert.ok(html.includes('name="description" content="'+seo.escapeHtml(page.description)+'"'),file+' description must agree with metadata');
  assert.ok(!titles.has(page.title));titles.add(page.title);
  assert.ok(!descriptions.has(page.description));descriptions.add(page.description);
  assert.match(html,/<h1[ >]/);
  assert.doesNotMatch(html,/href="\/?(?:index|recorrido|cotizacion|plano|comunidad|contacto)\.html/,'Internal links should target canonical paths');
}
for(const path of ['/admin','/api/catalogo','/unknown','/recorrido/extra','/recorrido.html/extra','/__proto__'])assert.equal(seo.canonicalPath(path),null);
assert.equal(seo.pageMetadata(origin,'/admin'),'');
assert.ok(!sitemap.includes('/admin')&&!sitemap.includes('/api/')&&!sitemap.includes('.html')&&!sitemap.includes('<lastmod>'));
assert.equal((sitemap.match(/<url>/g)||[]).length,Object.keys(seo.PUBLIC_PAGES).length);
assert.match(seo.robotsText(origin),/Sitemap: https:\/\/morada.test\/sitemap.xml/);
assert.equal(seo.escapeHtml('<x a="&">'),'&lt;x a=&quot;&amp;&quot;&gt;');
const home=fs.readFileSync('public/home-polish.js','utf8');
assert.ok(!home.includes("description.textContent='Uchumayo, Arequipa. Bien inmueble futuro.'"),'Do not erase useful location and project copy after rendering');
console.log('PASS: unique crawlable metadata, safe structured data, consistent sitemap/canonicals, alias normalization, private-page exclusion and static/rendered content alignment.');
